"""Parses the commissioner's supplied 5-tier tables (qa/supplied_tables_v2.txt, copied verbatim from chat) into
functions/tablesV2.ts. Usage: python3 qa/parse_tables_v2.py"""
import os, re
HERE = os.path.dirname(__file__)
src = open(os.path.join(HERE, "supplied_tables_v2.txt")).read()
NAME = {"55m Hurdles": "55m Hurdles", "60m Hurdles": "60m Hurdles", "100m Hurdles": "100m Hurdles", "110m Hurdles": "110m Hurdles",
        "300m Hurdles": "300m Hurdles", "400m Hurdles": "400m Hurdles"}
tables, cur = [], None
for line in src.splitlines():
    line = line.strip()
    m = re.match(r"^(Boys|Girls) (.+)$", line)
    if m and "➔" not in line:
        cur = {"gender": "B" if m.group(1) == "Boys" else "G", "event": NAME.get(m.group(2), m.group(2)), "tiers": []}
        tables.append(cur); continue
    m = re.match(r"^([0-9:.\-]+) or (faster|higher|farther) ➔ ([0-9.]+)$", line)
    if m and cur: cur["tiers"].append((m.group(1), float(m.group(3))))
assert all(len(t["tiers"]) == 5 for t in tables), [t for t in tables if len(t["tiers"]) != 5]
assert all([p for _, p in t["tiers"]] == [0.5, 1.5, 2.5, 4.5, 7.0] for t in tables)
out = ["// Generated by qa/parse_tables_v2.py from qa/supplied_tables_v2.txt (commissioner's 5-tier tables, Oct 2026). Do not edit by hand.",
       'import type { Gender } from "./scoring";', "",
       "export const OFFICIAL_TABLES_V2: { gender: Gender; event: string; tiers: [string, number][] }[] = ["]
for t in tables:
    tiers = ", ".join(f'["{m}", {p:g}]' for m, p in t["tiers"])
    out.append(f'  {{ gender: "{t["gender"]}", event: "{t["event"]}", tiers: [{tiers}] }},')
out.append("];")
open(os.path.join(HERE, "..", "functions", "tablesV2.ts"), "w").write("\n".join(out) + "\n")
print(len(tables), "tables", sum(1 for t in tables if t["gender"] == "B"), "boys")
